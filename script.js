function addTerminalLine(text, className = "terminal-output-line") {
  const line = document.createElement("p");
  line.className = `terminal-line ${className}`;
  line.textContent = text;
  terminalOutput.append(line);
  terminalOutput.scrollTop = terminalOutput.scrollHeight;
}

terminalForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const command = terminalInput.value.trim().toLowerCase();
  if (!command) return;
  terminalInput.value = "";

  if (command === "clear") {
    terminalOutput.replaceChildren();
    gameTarget = null;
    gameAttempts = 0;
    return;
  }
  if (gameTarget !== null && command === "exit") {
    gameTarget = null;
    gameAttempts = 0;
    addTerminalLine(translations[language]["terminal.gameExit"], "terminal-muted");
    return;
  }
  if (gameTarget !== null) {
    const guess = Number(command);
    const answer = command.replace(/\s+/g, "");
    if (!["6", "3+3", "9-3"].includes(answer)) {
      addTerminalLine(translations[language]["terminal.gameInvalid"], "terminal-muted");
      return;
    }
    gameAttempts += 1;
    if (answer === "6" || answer === "3+3" || answer === "9-3") {
      addTerminalLine(translations[language]["terminal.gameWin"].replace("{attempts}", gameAttempts), "terminal-success");
      gameTarget = null;
      gameAttempts = 0;
    }
    return;
  }
  if (command === "help") {
    addTerminalLine(translations[language]["terminal.help"], "terminal-success");
    return;
  }
  addTerminalLine(`$ ${command}`, "terminal-command");
  if (command === "cv") {
    addTerminalLine(translations[language]["terminal.cv"], "terminal-success");
    cvDownload.click();
    return;
  }
  if (command === "contact") {
    addTerminalLine(translations[language]["terminal.contact"], "terminal-success");
    window.location.href = "mailto:01enmanuelromero@gmail.com";
    return;
  }
  if (command === "game") {
    gameTarget = 6;
    gameAttempts = 0;
    addTerminalLine(translations[language]["terminal.gameStart"], "terminal-success");
    return;
  }
  addTerminalLine(translations[language]["terminal.unknown"], "terminal-muted");
});

const canvas = document.querySelector("#particle-canvas");
const context = canvas.getContext("2d");
const particles = [];

function resizeCanvas() {
  const ratio = window.devicePixelRatio || 1;
  canvas.width = window.innerWidth * ratio;
  canvas.height = window.innerHeight * ratio;
  context.setTransform(ratio, 0, 0, ratio, 0, 0);
}

function createParticles() {
  particles.length = 0;
  const count = Math.min(95, Math.floor(window.innerWidth / 13));
  for (let particleIndex = 0; particleIndex < count; particleIndex += 1) {
    particles.push({
      x: Math.random() * window.innerWidth,
      y: Math.random() * window.innerHeight,
      size: Math.random() * 2.4 + .5,
      speed: Math.random() * .28 + .08,
      drift: (Math.random() - .5) * .18,
      color: Math.random() > .83 ? "#c084fc" : "#8de7df",
    });
  }
}

function animateParticles() {
  context.clearRect(0, 0, window.innerWidth, window.innerHeight);
  particles.forEach((particle) => {
    particle.y -= particle.speed;
    particle.x += particle.drift;
    if (particle.y < -10) particle.y = window.innerHeight + 10;
    if (particle.x < -10) particle.x = window.innerWidth + 10;
    if (particle.x > window.innerWidth + 10) particle.x = -10;
    context.globalAlpha = .25 + particle.size / 4;
    context.fillStyle = particle.color;
    context.fillRect(particle.x, particle.y, particle.size, particle.size);
  });
  requestAnimationFrame(animateParticles);
}

resizeCanvas();
createParticles();
window.addEventListener("resize", () => {
  resizeCanvas();
  createParticles();
});
animateParticles();

